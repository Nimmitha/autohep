#!/usr/bin/env python3
"""Generate ready-to-submit CRAB configurations for the HUMAN operator.

The framework cannot authenticate to the grid (no VOMS proxy off-site), so when a
study needs new collaboration data or MC, this tool emits a complete
crabConfig_<tag>.py + submit script that the user reviews and submits on an
LPC/lxplus node. Nothing here talks to the grid.

Inputs are a job spec (JSON or CLI flags):
{
  "request_name": "TTree_13TeV_zeejmm_UL_2018C",
  "input_dataset": "/EGamma/Run2018C-UL2018_MiniAODv2-v1/MINIAOD",
  "psetname": "run_TTree_cfg.py",
  "lumi_mask": "Cert_314472-325175_13TeV_Legacy2018_Collisions18_JSON.txt",
  "units_per_job": 50,                      # LumiBased splitting
  "out_lfn_base": "/store/user/<user>/autohep",
  "storage_site": "T3_US_FNALLPC",
  "is_mc": false
}

CLI:
    crab_configgen.py --spec spec.json --out-dir crab/2018C/
    crab_configgen.py --request-name X --input-dataset /A/B/MINIAOD \
        --psetname cfg.py --out-dir crab/
"""
from __future__ import annotations

import argparse
import json
import os
import sys

CRAB_TEMPLATE = """\
# Generated by autohep crab_configgen — review before submitting.
# Submit on an LPC/lxplus node with a valid VOMS proxy:
#   voms-proxy-init -voms cms -valid 192:00
#   crab submit -c {config_name}
from CRABClient.UserUtilities import config

config = config()

config.General.requestName = '{request_name}'
config.General.workArea = 'crab_projects'
config.General.transferOutputs = True
config.General.transferLogs = False

config.JobType.pluginName = 'Analysis'
config.JobType.psetName = '{psetname}'
config.JobType.allowUndistributedCMSSW = True

config.Data.inputDataset = '{input_dataset}'
config.Data.inputDBS = 'global'
config.Data.splitting = '{splitting}'
config.Data.unitsPerJob = {units_per_job}
{lumi_mask_line}
config.Data.publication = False
config.Data.outLFNDirBase = '{out_lfn_base}'
config.Data.outputDatasetTag = '{request_name}'

config.Site.storageSite = '{storage_site}'
"""

SUBMIT_TEMPLATE = """\
#!/bin/bash
# Generated by autohep crab_configgen. Run on LPC/lxplus after `cmsenv`.
set -euo pipefail
if ! voms-proxy-info -exists -valid 8:0 2>/dev/null; then
  echo "No valid VOMS proxy. Run: voms-proxy-init -voms cms -valid 192:00" >&2
  exit 1
fi
crab submit -c {config_name}
"""

REQUIRED = ("request_name", "input_dataset", "psetname")


def generate(spec: dict, out_dir: str) -> dict:
    missing = [k for k in REQUIRED if not spec.get(k)]
    if missing:
        raise ValueError(f"spec missing required keys: {missing}")
    if not spec["input_dataset"].count("/") >= 3:
        raise ValueError(f"input_dataset does not look like a DAS path: "
                         f"{spec['input_dataset']!r}")
    is_mc = bool(spec.get("is_mc", False))
    lumi_mask = spec.get("lumi_mask", "")
    if not is_mc and not lumi_mask:
        raise ValueError("collision-data spec requires a lumi_mask (golden JSON); "
                         "set is_mc=true for simulation")
    values = {
        "request_name": spec["request_name"],
        "input_dataset": spec["input_dataset"],
        "psetname": spec["psetname"],
        "splitting": spec.get("splitting", "FileBased" if is_mc else "LumiBased"),
        "units_per_job": int(spec.get("units_per_job", 10 if is_mc else 50)),
        "lumi_mask_line": (f"config.Data.lumiMask = '{lumi_mask}'"
                           if lumi_mask else "# MC: no lumi mask"),
        "out_lfn_base": spec.get("out_lfn_base", "/store/user/CHANGE_ME/autohep"),
        "storage_site": spec.get("storage_site", "T3_US_FNALLPC"),
        "config_name": f"crabConfig_{spec['request_name']}.py",
    }
    os.makedirs(out_dir, exist_ok=True)
    cfg_path = os.path.join(out_dir, values["config_name"])
    with open(cfg_path, "w") as f:
        f.write(CRAB_TEMPLATE.format(**values))
    sub_path = os.path.join(out_dir, f"submit_{spec['request_name']}.sh")
    with open(sub_path, "w") as f:
        f.write(SUBMIT_TEMPLATE.format(**values))
    os.chmod(sub_path, 0o755)
    notes = []
    if "CHANGE_ME" in values["out_lfn_base"]:
        notes.append("out_lfn_base uses CHANGE_ME — set your /store/user area")
    return {"config": cfg_path, "submit_script": sub_path, "notes": notes}


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--spec", help="JSON job spec file")
    p.add_argument("--request-name")
    p.add_argument("--input-dataset")
    p.add_argument("--psetname")
    p.add_argument("--lumi-mask", default="")
    p.add_argument("--is-mc", action="store_true")
    p.add_argument("--units-per-job", type=int)
    p.add_argument("--out-lfn-base")
    p.add_argument("--storage-site")
    p.add_argument("--out-dir", required=True)
    a = p.parse_args(argv)
    spec = {}
    if a.spec:
        with open(a.spec) as f:
            spec = json.load(f)
    for k in ("request_name", "input_dataset", "psetname", "lumi_mask",
              "units_per_job", "out_lfn_base", "storage_site"):
        v = getattr(a, k.replace("-", "_"), None)
        if v not in (None, ""):
            spec[k] = v
    if a.is_mc:
        spec["is_mc"] = True
    result = generate(spec, a.out_dir)
    print(json.dumps(result, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
